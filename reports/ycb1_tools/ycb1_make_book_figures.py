"""Generate LaTeX/books/YCB1/book/ycb1_book_figures.tex from docs/image_register.csv.
Defines, for every register figure, its prompt and final file name, for the book macro \\ycbfig{<figure_id>}.
Re-run after the register changes. Figures that say 'Do not generate' (table screenshots, portraits) get no entry.
"""
import csv, io, os, re
B = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "LaTeX", "books", "YCB1")) + os.sep
def esc(s):
    s = s.replace("\\", "/")
    for a, b in [("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("$", "\\$"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")]:
        s = s.replace(a, b)
    return s
out = ["% Generated by reports/ycb1_tools/ycb1_make_book_figures.py from docs/image_register.csv. Do not edit by hand.",
       "% One prompt and one final file per figure, used by \\ycbfig{<figure_id>} (see template_book.tex).", ""]
n = 0
for r in csv.DictReader(io.open(B + "docs/image_register.csv", encoding="utf-8")):
    p = r["generation_prompt_or_brief"].strip()
    p = re.sub(r"\s*Used in block [^,]+, frame '[^']*'\.\s*", " ", p).strip()
    p = re.sub(r"^Used in block [^,]+, frame '[^']*'\.\s*", "", p)
    p = re.sub(r"\s*Check before use:.*$", "", p)
    fid = r["figure_id"]
    fn = os.path.basename(r["final_path"] or "")
    out.append("\\expandafter\\def\\csname figprompt@%s\\endcsname{%s}" % (fid, esc(p)))
    out.append("\\expandafter\\def\\csname figfile@%s\\endcsname{../workshop/images/new/%s}" % (fid, fn))
    n += 1
io.open(B + "book/ycb1_book_figures.tex", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("figures with prompts:", n)
