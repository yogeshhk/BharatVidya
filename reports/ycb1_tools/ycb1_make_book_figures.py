"""Generate LaTeX/books/YCB1/book/ycb1_book_figures.tex from docs/image_register.csv.
For every register figure it defines, for the book macro \\ycbfig{<figure_id>}: the prompt, the final
(replacement) file, the original workshop file, a clearance flag (risk high = permission to be cleared
before print) and an optional credit (register column `credit`, empty until a source is known).
Table screenshots are not placed (they are retyped as tables); figures that say 'Do not generate' keep
their brief as the prompt line. Re-run after the register changes.
"""
import csv, io, os, re
B = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "LaTeX", "books", "YCB1")) + os.sep
def esc(s):
    s = s.replace("\\", "/")
    for a, b in [("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("$", "\\$"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")]:
        s = s.replace(a, b)
    return s
def d(name, fid, val):
    return "\\expandafter\\def\\csname %s@%s\\endcsname{%s}" % (name, fid, val)
out = ["% Generated by reports/ycb1_tools/ycb1_make_book_figures.py from docs/image_register.csv. Do not edit by hand.",
       "% Per figure: prompt, final file, original file, clearance flag, credit; used by \\ycbfig{<figure_id>}.", ""]
n = 0
for r in csv.DictReader(io.open(B + "docs/image_register.csv", encoding="utf-8")):
    fid = r["figure_id"]
    p = r["generation_prompt_or_brief"].strip()
    p = re.sub(r"\s*Used in block [^,]+, frame '[^']*'\.\s*", " ", p).strip()
    p = re.sub(r"\s*Check before use:.*$", "", p)
    out.append(d("figprompt", fid, esc(p)))
    out.append(d("figfile", fid, "../images/new/%s" % os.path.basename(r["final_path"] or "")))
    if r["type"] != "table_screenshot":
        out.append(d("figorig", fid, "../images/%s" % r["current_name"]))
    if r["status"] == "drawn":
        out.append(d("figdrawn", fid, "1"))
    if r["risk"] == "high":
        out.append(d("figclear", fid, "1"))
    if (r.get("credit") or "").strip():
        out.append(d("figcredit", fid, esc(r["credit"].strip())))
    n += 1
io.open(B + "book/ycb1_book_figures.tex", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("figures:", n)
