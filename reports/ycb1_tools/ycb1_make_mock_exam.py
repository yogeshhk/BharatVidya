"""Build the book appendix book/ycb1_book_mock-exam.tex from the "Mock exam" section of docs/Notes YCB1.md.
The notes are the master: edit questions there, then re-run this script. Question numbers are generated by LaTeX
(\label and \ref); nothing is typed by hand. Usage: python -I ycb1_make_mock_exam.py"""
import io, os, re

B = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "LaTeX", "books", "YCB1")) + os.sep
notes = io.open(B + "docs/Notes YCB1.md", encoding="utf-8").read()
sec = notes.split("## Mock exam", 1)[1]
sec = re.split(r"\n## ", sec, 1)[0]

def tex(s):
    s = s.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("$", "\\$")):
        s = s.replace(a, b)
    s = re.sub(r'"([^"]+)"', r"``\1''", s)
    return s

parts, cur, q = [], None, None
for line in sec.split("\n"):
    m = re.match(r"^\*\*(.+)\*\*\s*$", line)
    if m:
        cur = {"title": m.group(1), "qs": []}; parts.append(cur); continue
    if line.startswith("- Q: ") and cur is not None:
        q = {"q": line[5:].strip()}; cur["qs"].append(q); continue
    m = re.match(r"^\s+- \(a\) (.+)$", line)
    if m and q is not None:
        q["opts"] = [o.strip() for o in re.split(r"\s*\([b-d]\)\s*", m.group(1))]; continue
    m = re.match(r"^\s+- Key: \(([a-d])\)\. Block: `([^`]+)`", line)
    if m and q is not None:
        q["key"], q["block"] = m.group(1), m.group(2)

n = 0
out = ["% Generated by reports/ycb1_tools/ycb1_make_mock_exam.py from the notes; do not edit by hand.",
       "\\chapter{Mock exam}\\label{ch:mock-exam}", "",
       "\\emph{Can you pass the theory paper today?} This paper follows the format of the Level 1 theory exam: "
       "multiple-choice questions of one mark each, two hours, and no negative marking. Answer every question, "
       "then check yourself with the key at the end. Each question comes from a chapter of this book, so a wrong "
       "answer points to the chapter to revise.", ""]
key = []
for p in parts:
    out += ["\\section*{%s}" % tex(p["title"]), "\\begin{enumerate}[resume*=mock]" if n else "\\begin{enumerate}[series=mock]"]
    for q in p["qs"]:
        n += 1
        assert len(q.get("opts", [])) == 4 and q.get("key"), q
        out.append("\\item\\label{mq:%d} %s" % (n, tex(q["q"])))
        out.append("\\begin{enumerate}[label=(\\alph*),nosep]")
        out += ["\\item %s" % tex(o) for o in q["opts"]]
        out.append("\\end{enumerate}")
        key.append("\\ref{mq:%d}~(%s)" % (n, q["key"]))
    out.append("\\end{enumerate}")
    out.append("")
out += ["\\section*{Answer key}", "{\\small " + "; ".join(key) + ".}", ""]
io.open(B + "book/ycb1_book_mock-exam.tex", "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("questions:", n, "parts:", len(parts))
